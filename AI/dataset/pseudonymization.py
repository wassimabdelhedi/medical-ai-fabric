"""
pseudonymization.py
-------------------
Étape 1 du pipeline IA :
- Charge ptbxl_database.csv
- Identifie les colonnes sensibles (patient_id, age, sex, nurse, site, device)
- Remplace patient_id par un case_id pseudonymisé (CASE001, CASE002, ...)
- Crée un fichier de correspondance sécurisé (NE PAS partager avec l'équipe Blockchain)
- Sauvegarde pseudonymized_database.csv sans les colonnes sensibles
"""

import pandas as pd
import os
import json
from datetime import datetime, timezone

# ─────────────────────────────────────────────
# CHEMINS
# ─────────────────────────────────────────────
BASE_DIR    = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATASET_DIR = os.path.join(BASE_DIR, "dataset")
OUTPUT_DIR  = os.path.join(BASE_DIR, "outputs")

PTBXL_CSV        = os.path.join(DATASET_DIR, "ptbxl_database.csv")
PSEUDO_CSV       = os.path.join(DATASET_DIR, "pseudonymized_database.csv")
MAPPING_FILE     = os.path.join(DATASET_DIR, "id_mapping_SECURE.json")   # NE PAS partager

# Colonnes contenant des informations personnelles à supprimer
SENSITIVE_COLUMNS = [
    "patient_id", "age", "sex", "height", "weight", "nurse", "site", "device",
    "recording_date", "heart_axis", "infarction_stadium1",
    "infarction_stadium2", "validated_by", "validated_by_human",
    "second_opinion", "initial_autogenerated_report",
]


def load_database(csv_path: str) -> pd.DataFrame:
    """
    Charge ptbxl_database.csv.
    Affiche les premières lignes et les colonnes disponibles pour exploration.
    """
    print(f"[INFO] Chargement de : {csv_path}")
    df = pd.read_csv(csv_path, index_col="ecg_id")
    print(f"[INFO] {len(df)} enregistrements chargés.")
    print(f"[INFO] Colonnes disponibles : {list(df.columns)}")
    return df


def assign_case_ids(df: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    """
    Génère un case_id unique pour chaque ECG.
    Format : CASE00001, CASE00002, ...

    Retourne :
      - df avec la nouvelle colonne 'case_id'
      - mapping dict { case_id -> patient_id original } (fichier sécurisé)
    """
    print("[INFO] Attribution des identifiants pseudonymisés...")

    # Génère les case_id dans l'ordre (zfill(5) = 5 chiffres : CASE00001)
    case_ids = [f"CASE{str(i+1).zfill(5)}" for i in range(len(df))]
    df = df.copy()
    df.insert(0, "case_id", case_ids)

    # Mapping sécurisé : case_id → patient_id original
    # Ce fichier doit rester confidentiel et hors blockchain
    mapping = {}
    if "patient_id" in df.columns:
        for cid, pid in zip(case_ids, df["patient_id"]):
            mapping[cid] = int(pid)

    print(f"[INFO] {len(case_ids)} case_ids générés (CASE00001 → CASE{str(len(df)).zfill(5)})")
    return df, mapping


def remove_sensitive_columns(df: pd.DataFrame) -> pd.DataFrame:
    """
    Supprime les colonnes sensibles du DataFrame.
    Seules les colonnes présentes dans le df sont supprimées (pas d'erreur si absente).
    """
    cols_to_drop = [c for c in SENSITIVE_COLUMNS if c in df.columns]
    df_clean = df.drop(columns=cols_to_drop)
    print(f"[INFO] Colonnes supprimées (données personnelles) : {cols_to_drop}")
    print(f"[INFO] Colonnes conservées : {list(df_clean.columns)}")
    return df_clean


def assign_labels(df: pd.DataFrame) -> pd.DataFrame:
    """
    Label binaire fondé sur les codes diagnostiques positifs PTB-XL :
      - Normal : NORM est le seul code diagnostique positif
      - Abnormal : au moins un code diagnostique positif autre que NORM
      - Unknown : aucun code diagnostique positif exploitable
    """
    import ast
    statements_path = os.path.join(DATASET_DIR, "scp_statements.csv")
    statements = pd.read_csv(statements_path, index_col=0)
    diagnostic_codes = set(
        statements.index[statements["diagnostic"] == 1].astype(str)
    )

    def get_label(scp_str):
        try:
            scp_dict = ast.literal_eval(str(scp_str))
            positive = {
                str(code) for code, likelihood in scp_dict.items()
                if str(code) in diagnostic_codes and float(likelihood) > 0
            }
            if not positive:
                return "Unknown"
            return "Normal" if positive == {"NORM"} else "Abnormal"
        except Exception:
            return "Unknown"

    df = df.copy()
    df["label"] = df["scp_codes"].apply(get_label)

    counts = df["label"].value_counts()
    print(f"[INFO] Distribution des labels :")
    for lbl, cnt in counts.items():
        print(f"       {lbl}: {cnt} ({cnt/len(df)*100:.1f}%)")
    return df


def save_pseudonymized_database(df: pd.DataFrame, mapping: dict):
    """
    Sauvegarde :
    1. pseudonymized_database.csv  → partageable avec l'équipe IA
    2. id_mapping_SECURE.json      → CONFIDENTIEL, ne pas partager
    """
    os.makedirs(DATASET_DIR, exist_ok=True)

    # 1. Base pseudonymisée
    df.to_csv(PSEUDO_CSV, index=True)
    print(f"[OK] Base pseudonymisée sauvegardée : {PSEUDO_CSV}")

    # 2. Fichier de correspondance sécurisé
    secure_data = {
        "created_at": datetime.now(timezone.utc).isoformat(),
        "warning": "FICHIER CONFIDENTIEL - NE PAS PARTAGER - NE PAS METTRE SUR BLOCKCHAIN",
        "mapping": mapping
    }
    with open(MAPPING_FILE, "w") as f:
        json.dump(secure_data, f, indent=2)
    print(f"[OK] Mapping sécurisé sauvegardé : {MAPPING_FILE}")
    print(f"[!]  IMPORTANT : ne partagez JAMAIS ce fichier de mapping.")


def run_pseudonymization():
    """
    Fonction principale — exécute toutes les étapes dans l'ordre.
    """
    print("=" * 60)
    print("  ÉTAPE 1 : PSEUDONYMISATION DU DATASET PTB-XL")
    print("=" * 60)

    # 1. Chargement
    df = load_database(PTBXL_CSV)

    # 2. Attribution des case_ids
    df, mapping = assign_case_ids(df)

    # 3. Attribution des labels (Normal / Abnormal)
    df = assign_labels(df)

    # 4. Supprime les métadonnées inutiles au modèle ECG et les quasi-identifiants.
    df_clean = remove_sensitive_columns(df)

    # 5. Sauvegarde
    save_pseudonymized_database(df_clean, mapping)

    print("=" * 60)
    print("  PSEUDONYMISATION TERMINÉE")
    print(f"  Enregistrements traités : {len(df_clean)}")
    print(f"  Fichier de sortie       : {PSEUDO_CSV}")
    print("=" * 60)
    return df_clean


if __name__ == "__main__":
    run_pseudonymization()
